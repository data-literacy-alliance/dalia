for _lang, _values in _WEBSITE_STRINGS.items():
    _values["partner_names"] = [name for name, _url in _PARTNERS]
    _values["partner_links"] = [{"name": name, "url": url} for name, url in _PARTNERS]
    _STRINGS[_lang].update(_values)


def get_strings(lang: str) -> dict:
    """Return a fresh dict of UI strings for ``lang``.

    Unknown languages fall back to English and keys missing in ``lang`` fall back to their English value.
    """
    merged = {**_STRINGS[DEFAULT_LANGUAGE], **_STRINGS.get(lang, {})}
    merged["partner_names"] = list(merged["partner_names"])
    merged["partner_links"] = [dict(link) for link in merged["partner_links"]]
    return merged
